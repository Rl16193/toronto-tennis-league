function crossAt(x1: number, y1: number, x2: number, y2: number, x: number, y: number): number {
  return (x2 - x1) * (y - y1) - (y2 - y1) * (x - x1);
}

// Which side of a west->east polyline a point falls on (bracketed by longitude). Positive = north.
function sideByLng(poly: Pt[], lng: number, lat: number): number {
  const n = poly.length - 1;
  if (lng <= poly[0][0]) return crossAt(poly[0][0], poly[0][1], poly[1][0], poly[1][1], lng, lat);
  if (lng >= poly[n][0]) return crossAt(poly[n - 1][0], poly[n - 1][1], poly[n][0], poly[n][1], lng, lat);
  for (let i = 0; i < n; i++) {
    const [x1, y1] = poly[i],
      [x2, y2] = poly[i + 1];
    const lo = Math.min(x1, x2),
      hi = Math.max(x1, x2);
    if (lng >= lo && lng <= hi) return crossAt(x1, y1, x2, y2, lng, lat);
  }
  return 0;
}

// Which side of a south->north polyline a point falls on (bracketed by latitude). Positive = west.
function sideByLat(poly: Pt[], lng: number, lat: number): number {
  const n = poly.length - 1;
  if (lat <= poly[0][1]) return crossAt(poly[0][0], poly[0][1], poly[1][0], poly[1][1], lng, lat);
  if (lat >= poly[n][1]) return crossAt(poly[n - 1][0], poly[n - 1][1], poly[n][0], poly[n][1], lng, lat);
  for (let i = 0; i < n; i++) {
    const [x1, y1] = poly[i],
      [x2, y2] = poly[i + 1];
    const lo = Math.min(y1, y2),
      hi = Math.max(y1, y2);
    if (lat >= lo && lat <= hi) return crossAt(x1, y1, x2, y2, lng, lat);
  }
  return 0;
}

// Fallback for the small sliver of points outside every real-road rule below (near dataset
// edges) — getZone() must always return something, and a rough zone beats an exception.
function rectangleFallback(lat: number, lng: number): ZoneName {
  if (lng < -79.435) {
    if (lat > 43.722) return 'York West';
    if (lat > 43.653) return 'Etobicoke';
    return 'Etobicoke - Lakeshore';
  } else if (lng <= -79.345) {
    return lat > 43.71 ? 'North York' : 'Downtown - Midtown';
  } else {
    return lat > 43.755 ? 'North Scarborough' : 'East York and South Scarborough';
  }
}

// Zone boundaries follow real streets/highways/rivers (City of Toronto Centreline dataset):
//  - Etobicoke: south of Hwy 401, north of St Clair Ave W -> Dundas St W, west of Dufferin St, east of the west city edge
//  - Etobicoke - Lakeshore: south of St Clair Ave W -> Dundas St W, west of Dufferin St, north of the lake
//  - York West: west of Bathurst St, between Steeles Ave (real northern edge) and Hwy 401, east of the west city edge
//  - Downtown - Midtown: between Dufferin St and the DVP/Hwy 404, south of Eglinton Ave, north of the lake
//  - North York: between Bathurst St and the DVP/Hwy 404, between Eglinton Ave and Steeles Ave
//  - North Scarborough: south of Steeles Ave, north of the east-edge road chain, east of the DVP/Hwy 404
//  - East York and South Scarborough: south of the east-edge road chain, north of the lake, east of the DVP/Hwy 404
export function getZone(lat: number, lng: number): ZoneName {
  const northOf401 = sideByLng(ROADS.hwy401, lng, lat) > 0;
  const eastOfDvp404 = sideByLat(DVP_404, lng, lat) < 0;
  const westOfDufferin = sideByLat(ROADS.dufferin, lng, lat) > 0;
  const westOfBathurst = sideByLat(ROADS.bathurst, lng, lat) > 0;
  const northOfEglinton = sideByLng(ROADS.eglinton, lng, lat) > 0;
  const northOfStClairDundas = sideByLng(ST_CLAIR_DUNDAS, lng, lat) > 0;
  const aboveLake = sideByLng(ROADS.waterfront, lng, lat) > 0;
  const northOfSteeles = sideByLng(ROADS.steeles, lng, lat) > 0;
  const northOfLawrence = sideByLng(ROADS.lawrence, lng, lat) > 0;
  const eastOfWestBoundary = sideByLat(WEST_BOUNDARY, lng, lat) < 0;
  const westOfEastBoundary = sideByLat(EAST_BOUNDARY, lng, lat) > 0;

  // South of 401, north of St Clair/Dundas — east edge is Bathurst above Eglinton (Ranee/Glencairn
  // area) but Dufferin below Eglinton, so this doesn't compete with Downtown - Midtown for the
  // Dufferin-Bathurst band south of Eglinton (Cedarvale/Humewood) — each zone owns one clean edge.
  if (!northOf401 && northOfStClairDundas && (northOfEglinton ? westOfBathurst : westOfDufferin) && eastOfWestBoundary)
    return 'Etobicoke';
  if (!northOfStClairDundas && westOfDufferin && aboveLake && eastOfWestBoundary) return 'Etobicoke - Lakeshore';
  if (westOfBathurst && northOf401 && !northOfSteeles && eastOfWestBoundary) return 'York West';
  if (!westOfDufferin && !eastOfDvp404 && !northOfEglinton && aboveLake) return 'Downtown - Midtown';
  if (!westOfBathurst && !eastOfDvp404 && northOfEglinton && !northOfSteeles) return 'North York';
  if (northOfLawrence && !northOfSteeles && eastOfDvp404 && westOfEastBoundary) return 'North Scarborough';
  if (!northOfLawrence && eastOfDvp404 && aboveLake && westOfEastBoundary) return 'East York and South Scarborough';

  return rectangleFallback(lat, lng);
}

