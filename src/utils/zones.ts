// Zone for a user whose courts span several zones: majority vote across their preferred courts,
// tie-broken to 'Downtown - Midtown' (best transit — someone split evenly is still most likely to
// make it downtown). Falls back to the first court with known coordinates.
export function zoneFromCourts(courts: string[], courtCoords: Map<string, { lat: number; lng: number }>): string {
  const zones = courts
    .map((c) => courtCoords.get(c.trim().toLowerCase()))
    .filter((c): c is { lat: number; lng: number } => !!c)
    .map((c) => getZone(c.lat, c.lng));
  if (zones.length === 0) return '';

  const counts = new Map<string, number>();
  zones.forEach((z) => counts.set(z, (counts.get(z) ?? 0) + 1));
  const maxCount = Math.max(...counts.values());
  const tied = [...counts.entries()].filter(([, n]) => n === maxCount).map(([z]) => z);
  if (tied.length === 1) return tied[0];
  return tied.includes('Downtown - Midtown') ? 'Downtown - Midtown' : tied[0];
}

export function haversineKm(lat1: number, lng1: number, lat2: number, lng2: number): number {
  const R = 6371;
  const dLat = ((lat2 - lat1) * Math.PI) / 180;
  const dLng = ((lng2 - lng1) * Math.PI) / 180;
  const a =
    Math.sin(dLat / 2) ** 2 +
    Math.cos((lat1 * Math.PI) / 180) * Math.cos((lat2 * Math.PI) / 180) * Math.sin(dLng / 2) ** 2;
  return R * 2 * Math.atan2(Math.sqrt(a), Math.sqrt(1 - a));
}

// Probes getZone() at 4 points ~1.2km away (N/S/E/W); any disagreement means the point is near a
// real boundary, and that neighbour is offered as the alternate. Works with whatever getZone()
// logic is in play, since it only reads the function's output.
const PROBE_DEG = 0.011; // ~1.2km at these latitudes
export function getZoneWithBorderCheck(lat: number, lng: number): { primary: ZoneName; adjacent: ZoneName | null } {
  const primary = getZone(lat, lng);
  const probes: [number, number][] = [
    [lat + PROBE_DEG, lng],
    [lat - PROBE_DEG, lng],
    [lat, lng + PROBE_DEG],
    [lat, lng - PROBE_DEG],
  ];
  for (const [pLat, pLng] of probes) {
    const other = getZone(pLat, pLng);
    if (other !== primary) return { primary, adjacent: other };
  }
  return { primary, adjacent: null };
}
